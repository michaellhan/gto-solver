"""Build gto/pf_equity.py: all-in preflop equity between the 169 hand classes (averaged over the
combo pairs that don't share a card), sampled over random boards. Used by the push/fold
equilibrium for short-stack jams.

    .venv/bin/python scripts/build_preflop_equity.py [boards]
"""
import base64
import os
import random
import sys
import zlib
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from gto.evaluator import eval_board                      # noqa: E402
from gto.pf_classes import COMPAT, class_sums             # noqa: E402

n_boards = int(sys.argv[1]) if len(sys.argv) > 1 else 3000
rng = random.Random(7)
win2 = np.zeros((1326, 1326), dtype=np.int32)   # 2 per win, 1 per tie
cnt = np.zeros((1326, 1326), dtype=np.int32)
for i in range(n_boards):
    s = eval_board(rng.sample(range(52), 5))
    ok = s >= 0
    live = ok[:, None] & ok[None, :]
    win2 += live * ((s[:, None] > s[None, :]) * 2 + (s[:, None] == s[None, :]))
    cnt += live
    if i % 500 == 0:
        print(i, file=sys.stderr)
eq = np.where(cnt > 0, win2 / np.maximum(2 * cnt, 1), 0.0)
num = class_sums(eq * COMPAT)
den = class_sums(COMPAT.astype(float))
m = np.where(den > 0, num / np.maximum(den, 1), 0.5)
blob = base64.b64encode(zlib.compress(np.round(m * 65535).astype("<u2").tobytes(), 9)).decode()
out = os.path.join(os.path.dirname(__file__), "..", "gto", "pf_equity.py")
with open(out, "w") as f:
    f.write('"""Generated by scripts/build_preflop_equity.py: all-in preflop equity between the hand\n'
            f'classes in gto.pf_classes.CLASSES order ({n_boards} random boards), uint16 / 65535."""\n')
    f.write("DATA = (\n")
    for j in range(0, len(blob), 96):
        f.write(f'    "{blob[j:j + 96]}"\n')
    f.write(")\n")
print("wrote", out, len(blob), "chars")
