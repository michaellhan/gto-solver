"""Build gto/pf_realize.py: how much of its equity each hand class realizes after a preflop call, measured
with the postflop solver, for the preflop subgame solver (gto/pf_solve.py).

For three standard 3bet pots (CO vs BTN, BTN vs BB, UTG vs CO) the subgame is solved, giving the
ranges that see a flop: in the 3bet pot, the opener's calls against the whole 3bet range; in the 4bet
pot, the 3bettor's calls against the opener's 4bets. Each is solved on a fixed sample of flops; a
combo's realized share of the pot is its EV over the pot, and its realization that share over its
preflop all-in equity against the other range. Summed by class (weighted by combo pairs and flops)
for each pot type and position, it becomes the table. The subgame is then solved again with the new
table and the measurement repeated (--rounds), since the ranges that see a flop depend on it.

  python scripts/build_realization.py                       # 2 rounds, 24 flops, 4s per solve
  python scripts/build_realization.py --flops 8 --budget 2  # quick look
"""
import argparse
import importlib
import os
import random
import sys
import time
from multiprocessing import Pool

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "gto", "pf_realize.py")


def cases():
    from calibrate_pf_solve import prepare
    return prepare()


def flop_sample(n, seed=11):
    rng = random.Random(seed)
    out = []
    while len(out) < n:
        f = tuple(sorted(rng.sample(range(52), 3)))
        if f not in out:
            out.append(f)
    return out


def measure(job):
    """One flop solve: per class, sum of pair-weighted realized share and of pair-weighted equity, for
    the out-of-position (0) and in-position (1) players."""
    board, r_oop, r_ip, pot, stack, budget = job
    from gto.solver import solve
    from gto.pf_classes import CLASS_OF, equity_vs, to_classes
    sol = solve(board, r_oop, r_ip, pot, stack, time_budget=budget)
    s, r0, r1, act = sol.solver, sol.r0, sol.r1, sol.ctx.active
    # EVs: the root player's from its action EVs (relative to its half of the pot: add it back to get its
    # share), the other's from a counterfactual pass (zero-sum around half the pot each)
    ev0 = (sol.root.avg_strategy0() * s.node_action_evs(sol.root, r0, r1)).sum(0)
    s.sampling = False
    u1 = s._cfr(sol.root, 1, r0[None, :], r1[None, :], update=False, use_avg=True)[0]
    s.sampling = True
    cs0, cs1 = s.compat_sum(r1[None, :])[0], s.compat_sum(r0[None, :])[0]
    share0 = ev0 / pot
    share1 = (np.where(cs1 > 1e-12, u1 / np.maximum(cs1, 1e-12), 0.0) + pot / 2) / pot
    out = []
    for rc, cs, share, r_opp in ((r0, cs0, share0, r_ip), (r1, cs1, share1, r_oop)):
        w = np.zeros(len(r_oop)); sh = np.zeros(len(r_oop))
        w[act] = rc * cs                         # pair weight of each combo on this board
        sh[act] = share
        eq = np.nan_to_num(equity_vs(r_opp), nan=0.0)
        out.append((to_classes(w * sh), to_classes(w * eq)))
    return out


def ranges_for(case):
    """The two flop spots of a case from the current subgame solve: (pot type, oop range, ip range,
    pot, stack behind, oop is the opener)."""
    import gto.pf_solve as P
    from gto.pf_classes import CLASS_OF
    from gto import preflop as pf
    name, wo, wt, spot = case[:4]
    S = P.solve(wo, wt, spot, iters=1500)
    ro_full, rt_full = case[5], case[6]
    o_call = ro_full * S["o_call"][CLASS_OF]
    o_4bet = ro_full * S["o_4bet"][CLASS_OF]
    t_call4 = rt_full * S["t_call"][CLASS_OF]
    pot3 = spot.pot + (spot.three - spot.open_in)
    pot4 = spot.pot + (spot.four - spot.open_in) + (spot.four - spot.three)
    out = []
    if spot.opener_ip:
        out.append(("3bet", rt_full, o_call, pot3, spot.stack - spot.three, False))
        out.append(("4bet", t_call4, o_4bet, pot4, spot.stack - spot.four, False))
    else:
        out.append(("3bet", o_call, rt_full, pot3, spot.stack - spot.three, True))
        out.append(("4bet", o_4bet, t_call4, pot4, spot.stack - spot.four, True))
    return out


def write_table(num, den, rounds, flops, budget):
    from gto.pf_classes import CLASSES
    lines = ['"""Generated by scripts/build_realization.py: per hand class, the share of its preflop all-in equity it',
             'realizes after a call sees a flop, measured with the postflop solver on the ranges of three standard',
             f'3bet pots ({rounds} rounds, {flops} flops, {budget}s per solve): [realization, weight relative to a',
             'typical class] per class, None where unmeasured. gto/pf_solve.py blends thin measurements with its',
             'parametric model."""',
             "TABLE = {"]
    for pt in ("3bet", "4bet"):
        lines.append(f'    "{pt}": {{')
        for pos in ("oop", "ip"):
            n, d = num[(pt, pos)], den[(pt, pos)]
            med = float(np.median(d[d > 0])) if (d > 0).any() else 1.0
            vals = [[round(float(n[i] / d[i]), 3), round(float(d[i] / med), 3)] if d[i] > 0 else None
                    for i in range(len(CLASSES))]
            lines.append(f'        "{pos}": {vals!r},')
        lines.append("    },")
    lines.append("}")
    lines.append(f"CLASSES = {list(CLASSES)!r}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flops", type=int, default=24)
    ap.add_argument("--budget", type=float, default=4.0)
    ap.add_argument("--rounds", type=int, default=2)
    ap.add_argument("--procs", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    args = ap.parse_args()
    sys.path.insert(0, HERE)
    import calibrate_pf_solve as C
    import gto.pf_solve as P
    from gto import preflop as pf
    # measurements accumulate over the rounds (each on the ranges the previous table gave), which damps
    # the fixed point and averages out sampling noise
    num = {(pt, pos): 0.0 for pt in ("3bet", "4bet") for pos in ("oop", "ip")}
    den = dict(num)
    for rnd in range(args.rounds):
        t0 = time.time()
        base = C.prepare()
        # full combo ranges alongside the class weights
        full = []
        for (o, t, s, four), case in zip(C.CASES, base):
            a = C.line(s)
            st = C.replay_hand(C.T, 100, {"preflop": a}, 1)[0]
            while st.to_act != o:
                a.append({"pos": st.to_act, "action": "fold"})
                st = C.replay_hand(C.T, 100, {"preflop": a}, 1)[0]
            R = pf.replay_ranges(a, C.T)
            full.append(case + (R[o], R[t]))
        flops = flop_sample(args.flops, seed=11 + rnd)
        jobs, keys = [], []
        for case in full:
            for pt, r_oop, r_ip, pot, stack, _ in ranges_for(case):
                for f in flops:
                    jobs.append((f, r_oop, r_ip, pot, stack, args.budget))
                    keys.append(pt)
        with Pool(args.procs) as pool:
            res = pool.map(measure, jobs)
        for pt, r in zip(keys, res):
            for pos, (n, d) in zip(("oop", "ip"), r):
                num[(pt, pos)] = num[(pt, pos)] + n
                den[(pt, pos)] = den[(pt, pos)] + d
        write_table(num, den, rnd + 1, args.flops, args.budget)
        importlib.reload(importlib.import_module("gto.pf_realize"))
        importlib.reload(P)
        print(f"round {rnd + 1}: {len(jobs)} solves in {time.time() - t0:.0f}s; "
              f"score vs charts {C.score(C.prepare(), 1500):.3f}")
        for pt in ("3bet", "4bet"):
            for pos in ("oop", "ip"):
                n, d = num[(pt, pos)], den[(pt, pos)]
                tot = float(np.sum(n) / max(np.sum(d), 1e-12))
                print(f"  {pt} {pos}: overall realization {tot:.3f}")


if __name__ == "__main__":
    main()
