"""Build gto/pf_game_data.py: MW_CORR, per hand class, its three-way all-in equity against two opponents over
the product of its heads-up equities against each, for the preflop game's three-way pots (gto/pf_game.py).

Given the board, two opponents' hands are close to independent, so the chance of beating both is about the
product of the chances of beating each: averaged over boards, E[p1 p2] = E[p1] E[p2] + cov, and the
covariance (a hand that beats one opponent on a board tends to beat the other) is what MW_CORR carries.
Opponents hold the top 30% of hands (the kind of range that sees a three-way flop).

    python scripts/build_three_way.py [boards]
"""
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import numpy as np
from gto.cards import ALL_COMBOS
from gto.evaluator import eval_board
from gto.pf_classes import CLASS_OF, COMPAT, N_IN, equity_vs
from gto.ranges import N_COMBOS


def top_range(share):
    s = np.nan_to_num(equity_vs(np.ones(N_COMBOS)))
    order = np.argsort(-s)
    r = np.zeros(N_COMBOS)
    r[order[:int(share * N_COMBOS)]] = 1.0
    return r


def main():
    n_boards = int(sys.argv[1]) if len(sys.argv) > 1 else 800
    rng = random.Random(3)
    villain = top_range(0.30)
    cards = np.array(ALL_COMBOS)
    s1 = np.zeros(N_COMBOS); s2 = np.zeros(N_COMBOS); cnt = np.zeros(N_COMBOS)
    for _ in range(n_boards):
        board = rng.sample(range(52), 5)
        st = eval_board(board)
        ok = st >= 0
        live = (ok[:, None] & ok[None, :] & COMPAT) * villain[None, :]
        win = ((st[:, None] > st[None, :]) + 0.5 * (st[:, None] == st[None, :])) * live
        mass = live.sum(1)
        p = np.where(mass > 0, win.sum(1) / np.maximum(mass, 1e-12), 0.0)
        s1 += ok * p; s2 += ok * p * p; cnt += ok
    e1 = np.bincount(CLASS_OF, weights=s1, minlength=169) / np.bincount(CLASS_OF, weights=cnt, minlength=169)
    e2 = np.bincount(CLASS_OF, weights=s2, minlength=169) / np.bincount(CLASS_OF, weights=cnt, minlength=169)
    corr = e2 / np.maximum(e1 ** 2, 1e-9)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gto", "pf_game_data.py")
    with open(out, "w") as f:
        f.write('"""Generated by scripts/build_three_way.py: per hand class (pf_classes.CLASSES order), its three-way\n'
                f'all-in equity against two top-30% ranges over the product of its heads-up equities ({n_boards} boards)."""\n')
        f.write(f"MW_CORR = {np.round(corr, 4).tolist()!r}\n")
    from gto.pf_classes import CLASSES
    for c in ("AA", "KK", "AKs", "T9s", "72o", "22", "A5s"):
        i = CLASSES.index(c)
        print(c, f"heads-up {e1[i]:.3f}, three-way {e2[i]:.3f}, corr {corr[i]:.3f}")


if __name__ == "__main__":
    main()
