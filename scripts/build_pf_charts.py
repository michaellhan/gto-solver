"""Build gto/pf_charts.py: charts taken from the derived preflop equilibrium (scripts/pf_equilibrium.py), for the
families of spots where it replaces the hand-written charts of gto/preflop.py (see FAMILIES).

Each chart is a line of the 6-max game (the non-fold actions before hero, everyone else folding) and, per
action, a 169-character string in pf_classes.CLASSES order: the class's frequency in twentieths, "a" (0) to
"u" (1). preflop.solved_chart() reads them.

    python scripts/build_pf_charts.py --round 2 [--cache DIR] [--families vs4bet]
"""
from __future__ import annotations
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)
import gto.native  # noqa: F401
import numpy as np

SEATS = ["UTG", "HJ", "CO", "BTN", "SB", "BB"]


def vs4bet():
    """The 3bettor facing the opener's 4bet, every seat pair, everyone else folded."""
    for i, o in enumerate(SEATS[:-1]):
        for t in SEATS[i + 1:]:
            yield [(o, "raise"), (t, "raise"), (o, "raise")], t


FAMILIES = {"vs4bet": vs4bet}


def encode(v: np.ndarray) -> str:
    return "".join(chr(ord("a") + int(round(float(x) * 20))) for x in np.clip(v, 0.0, 1.0))


def key_of(line, hero) -> str:
    return hero + "|" + ",".join(p + ("r" if a in ("raise", "all-in") else "c") for p, a in line)


def main():
    import pf_equilibrium as P
    from pf_compare import node_after
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--tag", default="")
    ap.add_argument("--rake", default="0.05,4")
    ap.add_argument("--cache", default=P.DEFAULT_CACHE)
    ap.add_argument("--families", default="vs4bet")
    args = ap.parse_args()
    rake = tuple(float(x) for x in args.rake.split(",")) if args.rake else None
    g = P.game(rake=rake)
    g.set_model(P.load_model(args.cache, args.round))
    g.load(os.path.join(args.cache, f"solve{args.round}{args.tag}.npz"))
    fams = args.families.split(",")
    charts = {}
    for fam in fams:
        for line, hero in FAMILIES[fam]():
            node = node_after(g, line, hero)
            s = g.strategy_at(node)
            charts[key_of(line, hero)] = {("raise" if k == "all-in" else k): encode(v) for k, v in s.items() if k != "fold"}
    out = os.path.join(ROOT, "gto", "pf_charts.py")
    with open(out, "w") as f:
        f.write('"""Generated by scripts/build_pf_charts.py: charts from the derived preflop equilibrium (scripts/pf_equilibrium.py,\n'
                f'round {args.round}, rake {rake}) for the spot families {fams}. Key: hero|the non-fold actions before it\n'
                '(position + r for a raise, c for a call); per action a class frequency string in pf_classes.CLASSES order,\n'
                '"a" = 0 to "u" = 1 in twentieths."""\n')
        f.write("CHARTS = {\n")
        for k in sorted(charts):
            f.write(f"    {k!r}: {charts[k]!r},\n")
        f.write("}\n")
    print(f"{len(charts)} charts -> {out}")


if __name__ == "__main__":
    main()
