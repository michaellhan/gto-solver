"""Fit gto/pf_realize_model.py: a smooth model of the excess pot shares measured by
scripts/build_realization.py (gto/pf_realize.py), for the preflop subgame solver (gto/pf_solve.py,
MODE = "model").

The measured table (per hand class against each opponent strength bucket: how far its pot share after a
call that sees a flop runs above its all-in equity) is noisy for single entries: a hand's postflop
result varies a lot from flop to flop. The model has a few coefficients per pot type, role and position, on
the hand's equity against the bucket (x = e - 0.5: x, x|x|) and its shape (pair, suited, connected,
pair*x, suited*x; pf_solve.MODEL_FEATURES), fitted by least squares weighted by how much each entry
rests on. Fitting the two halves of the flops (tests/data) shows how stable the coefficients are.

  python scripts/fit_realization.py                     # fit gto/pf_realize.py -> gto/pf_realize_model.py
  python scripts/fit_realization.py --halves tests/data # also fit each half -> tests/data/pf_realize_model_{a,b}.py
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
from gto import pf_solve as P

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "gto", "pf_realize_model.py")


def load(path):
    ns = {}
    with open(path) as f:
        exec(f.read(), ns)
    return ns["TABLE"]


def fit(table):
    """Coefficients per pot type and position, and the weighted R^2 of each fit."""
    np.seterr(all="ignore")              # macOS Accelerate's matmul raises spurious warnings
    X_all = P.model_features(P._bucket_equity())          # (K, buckets, features)
    coef, r2 = {}, {}
    for pt in ("3bet", "4bet"):
        coef[pt], r2[pt] = {}, {}
        for pos in table[pt]:
            X, y, w = [], [], []
            for i, row in enumerate(table[pt][pos]):
                for b, v in enumerate(row):
                    if v is not None:
                        X.append(X_all[i, b]); y.append(v[0]); w.append(v[1])
            X, y, w = np.array(X), np.array(y), np.array(w)
            sw = np.sqrt(w)
            beta = np.linalg.lstsq(X * sw[:, None], y * sw, rcond=None)[0]
            mean = (w * y).sum() / w.sum()
            r2[pt][pos] = float(1 - (w * (y - X @ beta) ** 2).sum() / (w * (y - mean) ** 2).sum())
            coef[pt][pos] = [round(float(c), 4) for c in beta]
    return coef, r2


def write(coef, r2, source, out):
    lines = ['"""Generated by scripts/fit_realization.py from ' + source + ': per pot type, role and position, the',
             'coefficients of the excess pot share model on pf_solve.MODEL_FEATURES ' + repr(P.MODEL_FEATURES) + '.',
             'Weighted R^2 of the fits: ' + ", ".join(f"{pt} {pos} {r2[pt][pos]:.2f}" for pt in r2 for pos in r2[pt]) + '."""',
             "COEF = {"]
    for pt in coef:
        lines.append(f'    "{pt}": {{' + ", ".join(f'"{pos}": {coef[pt][pos]!r}' for pos in coef[pt]) + "},")
    lines.append("}")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--halves", help="directory holding pf_realize_a.py and pf_realize_b.py to fit too")
    args = ap.parse_args()
    table = load(os.path.join(HERE, "..", "gto", "pf_realize.py"))
    coef, r2 = fit(table)
    write(coef, r2, "gto/pf_realize.py", OUT)
    print("full:", {pt: {pos: round(r2[pt][pos], 2) for pos in r2[pt]} for pt in r2})
    if args.halves:
        for h in "ab":
            c, r = fit(load(os.path.join(args.halves, f"pf_realize_{h}.py")))
            write(c, r, f"pf_realize_{h}.py", os.path.join(args.halves, f"pf_realize_model_{h}.py"))
            print(f"half {h}:", {pt: {pos: round(r[pt][pos], 2) for pos in r[pt]} for pt in r})


if __name__ == "__main__":
    main()
